// Run with deno run --allow-read --allow-write scripts/sync-exercise-metadata.ts.
// The server catalog is the source; Android and web consume this generated map.
import { EXERCISE_CATALOG } from "../supabase/functions/_shared/exercise_catalog.ts";
import { requirements } from "../supabase/functions/_shared/exercise_requirements.ts";
const entries = EXERCISE_CATALOG.map(e => ({ name: e.name, ...requirements(e) }));
await Deno.writeTextFile(new URL("../shared/exercise_metadata.json", import.meta.url), JSON.stringify(entries, null, 2) + "\n");
const q = (s: string) => JSON.stringify(s);
const kotlin = `package com.workoutmaker.app.strength
// Generated by scripts/sync-exercise-metadata.ts. Do not edit by hand.
data class ExerciseMetadata(val id: String, val movement: String, val implements: List<String>, val difficulty: String, val quantityUnit: String, val loadMode: String)
object ExerciseMetadataCatalog {
    val byName: Map<String, ExerciseMetadata> = mapOf(
${entries.map(e => `        ${q(e.name)} to ExerciseMetadata(${q(e.id)}, ${q(e.movement)}, listOf(${e.implements.map(q).join(", ")}), ${q(e.difficulty)}, ${q(e.logging === "distance" ? "metres" : e.logging)}, ${q(e.load_mode)}),`).join("\n")}
    )
    val implements: List<String> get() = byName.values.flatMap { it.implements }.distinct().sorted()
}
`;
await Deno.writeTextFile(new URL("../android/app/src/main/java/com/workoutmaker/app/strength/ExerciseMetadataCatalog.kt", import.meta.url), kotlin);
